	const SystemDefinition* findSystemDefinition(const std::string& name)
	{
		for (const auto& definition : SYSTEM_DEFINITIONS)
			if (name == definition.name)
				return &definition;

		return nullptr;
	}

	bool isSafeSystemName(const std::string& name)
	{
		if (name.empty() || name.size() > 64 || name[0] == '.' || name[0] == '-')
			return false;

		for (char c : name)
		{
			if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_' && c != '-' && c != '.' && c != '+')
				return false;
		}

		return true;
	}

	std::string systemConfigFileName(const std::string& system)
	{
		return "es_systems_" + system + ".cfg";
	}

	std::string buildEmulatorCommand(const InstalledItem& item)
	{
		if (item.command.empty())
			return "";

		std::string command;
		for (const auto& argument : item.command)
		{
			if (!command.empty())
				command += ' ';
			command += Utils::String::shellQuote(argument);
		}

		return command + " %ROM%";
	}

	std::string generatedConfigMarker()
	{
		return GENERATED_MARKER;
	}

	pugi::xml_node addEmulator(pugi::xml_node system, const std::string& id, const std::string& command)
	{
		pugi::xml_node emulators = system.child("emulators");
		if (!emulators)
			emulators = system.append_child("emulators");

		for (auto emulator : emulators.children("emulator"))
		{
			if (id != emulator.attribute("name").value())
				continue;

			// An entry the user already had is not ours: leave its command alone,
			// and do not mark it, so an uninstall does not remove it.
			if (!emulator.attribute("catalog").as_bool())
				return emulator;

			if (!command.empty())
				emulator.attribute("command").set_value(command.c_str());
			return emulator;
		}

		auto emulator = emulators.append_child("emulator");
		emulator.append_attribute("name").set_value(id.c_str());
		emulator.append_attribute("catalog").set_value("true");
		if (!command.empty())
			emulator.append_attribute("command").set_value(command.c_str());
		return emulator;
	}

	pugi::xml_node appendSystem(pugi::xml_node systemList, const std::string& system,
		const SystemDefinition* definition, pugi::xml_node existing,
		const std::string& emulatorId, const std::string& command, bool full)
	{
		auto node = systemList.append_child("system");
		node.append_child("name").text().set(system.c_str());

		if (full)
		{
			if (existing)
			{
				for (auto child : existing.children())
				{
					const std::string tag = child.name();
					if (tag == "name" || tag == "emulators")
						continue;
					node.append_copy(child);
				}
			}
			else if (definition)
			{
				node.append_child("fullname").text().set(definition->fullName);
				node.append_child("path").text().set(("~/ROMs/" + system).c_str());
				node.append_child("extension").text().set(definition->extensions);
				node.append_child("command").text().set(command.empty() ? "%EMULATOR% %ROM%" : command.c_str());
				node.append_child("platform").text().set(definition->platform);
				node.append_child("theme").text().set(definition->theme);
			}
		}

		auto emulators = node.append_child("emulators");
		if (existing)
		{
			if (auto old = existing.child("emulators"))
				for (auto emulator : old.children("emulator"))
					emulators.append_copy(emulator);
		}

		addEmulator(node, emulatorId, command);
		return node;
	}

